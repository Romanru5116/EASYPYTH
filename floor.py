# решаем задачу определеняи красоты плитки. Если в узоре 4х4 есть квадрат 2х2 плитки одног цвета. Симпатичным узором считается тот, который не содержит в себе квадрата 2х2, состоящего из плиток одного цвета.
# флаг found, который помогает полностью выйти из двух вложенных циклов при первом найденном совпадении.
grid = [input().strip() for _ in range(4)]

found = False
for i in range(3):
    for j in range(3):
        # Проверяем квадрат 2x2 с левым верхним углом (i, j)
        c = grid[i][j]
        if grid[i][j + 1] == c and grid[i + 1][j] == c and grid[i + 1][j + 1] == c:
            print("No")
            found = True
            break
    if found:
        break

if not found:
    print("Yes")
