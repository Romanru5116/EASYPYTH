# главную диагональ заполним 10
# еще треугольники под диагоналями и над диагоналями

n = int(input('Введите размер квадратной матрицы: '))

a = []
for i in range(n):
    a.append([0] * n)  # Создаем строку из n элементов

for i in range(n):
    for j in range(n):
        if i == j:
            a[i][j] = 10  # Главная диагональ
        elif i > j:
            a[i][j] = 3   # Нижний левый треугольник
        else:
            a[i][j] = 5   # Верхний правый треугольник

# Вывод матрицы
for row in a:
    print(row)
